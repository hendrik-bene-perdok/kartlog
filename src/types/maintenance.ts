/**
 * Type guard for checking if a task is auto-generated
 */
export function isAutoGeneratedTask(task: MaintenanceTask): task is MaintenanceTask & { autoGeneratedType: string } {
    return task.isAutoGenerated && !!task.autoGeneratedType;
}

/**
 * Type guard for checking if shopping item has photo
 */
export function hasPhoto(item: ShoppingListItem): item is ShoppingListItem & { photoId: string } {
    return !!item.photoId;
}

/**
 * Type guard for checking if shopping item is archived
 */
export function isArchived(item: ShoppingListItem): boolean {
    return item.status === 'archived';
}
